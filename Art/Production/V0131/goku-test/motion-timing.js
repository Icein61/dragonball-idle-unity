function timeline(action, branchSelected) {
  if (!action.branch || !branchSelected) return action;
  const extra = action.branch;
  return {
    ...action,
    duration: extra.duration,
    poses: [...action.poses.filter(([time]) => time < extra.split), ...extra.poses],
    root: [...action.root.filter(([time]) => time < extra.root[0][0]), ...extra.root],
    impacts: [...action.impacts, ...extra.impacts]
  };
}
